//! The plugins reference: the compiled-in system plugins and the contributions they offer.
//!
//! It is rendered from the catalog the application composes, so it cannot drift from the code.
//! A test compares it with `docs/reference/plugins.md` and rewrites that file on request.
use std::fmt::Write as _;

use nocterm_plugin_model::{
    AutoPlace, ChoiceOption, ContributionKind, FieldKind, FieldSpec, PluginCatalog,
    SystemContribution, SystemPlugin, Zone,
};

const HEADER: &str = "<!-- Generated by `NOCTERM_BLESS=1 cargo test -p nocterm plugins_reference`. Do not edit by hand. -->\n\n";

/// The text of `docs/reference/plugins.md` for a catalog.
pub(crate) fn render(catalog: &PluginCatalog) -> String {
    let mut text = format!(
        "{HEADER}# Plugins reference\n\nThe system plugins compiled into Nocterm, and the panels and widgets they and the shell offer to the window. A contribution's placement is a hint: the Default layout places it by zone and order, and a saved layout may place it elsewhere. Every plugin is enabled by default; `[plugins].disabled` lists those switched off, and a required plugin ignores it.\n\n"
    );
    text.push_str("## Panel groups\n\nPanels in one group exclude each other. The primary group holds the sidebar.\n\n| Group | Title | Primary |\n| --- | --- | --- |\n");
    for group in catalog.groups() {
        let _ = writeln!(
            text,
            "| `{}` | {} | {} |",
            group.id.as_str(),
            cell(group.title),
            yes(group.primary)
        );
    }
    let core: Vec<_> = catalog
        .entries()
        .filter(|contribution| catalog.plugin_of(&contribution.id).is_none())
        .collect();
    text.push_str("\n## Shell\n\nContributions of the window shell and its core features. They are not plugins and cannot be switched off.\n\n");
    contributions(&mut text, &core);
    for plugin in catalog.plugins() {
        plugin_section(&mut text, plugin);
    }
    text
}

fn plugin_section(text: &mut String, plugin: &SystemPlugin) {
    let _ = write!(
        text,
        "\n## {}\n\nPlugin `{}`. Required: {}. Enabled by default: yes.",
        plugin.name,
        plugin.id.as_str(),
        yes(plugin.required),
    );
    if let Some(page) = plugin.settings_page {
        let _ = write!(
            text,
            " Own settings page: `{page}`, reached from Settings \u{25b8} Plugins."
        );
    }
    let _ = write!(text, "\n\n{}\n\n", plugin.description);
    let all: Vec<_> = plugin.contributions.iter().collect();
    contributions(text, &all);
    settings(text, plugin);
}

/// One table per settings group: the fields a plugin exposes and where they are stored.
fn settings(text: &mut String, plugin: &SystemPlugin) {
    let Some(section) = plugin.settings_section else {
        return;
    };
    for group in plugin.settings.groups.iter() {
        let _ = write!(text, "\n### Settings: {}\n\n", cell(&group.title));
        if let Some(contribution) = &group.contribution {
            let _ = write!(text, "Shown for `{contribution}`.\n\n");
        }
        text.push_str("| Key | Label | Kind | Default | Options or range | Stored in |\n| --- | --- | --- | --- | --- | --- |\n");
        for field in group.fields.iter() {
            let (kind, default, options) = describe(field);
            let _ = writeln!(
                text,
                "| `{}` | {} | {} | {} | {} | `[{section}].{}` |",
                field.key,
                cell(&field.label),
                kind,
                cell(&default),
                cell(&options),
                field.key
            );
        }
    }
}

fn describe(field: &FieldSpec) -> (&'static str, String, String) {
    match &field.kind {
        FieldKind::Toggle { default } => (
            "toggle",
            on_off(*default).to_owned(),
            "on or off".to_owned(),
        ),
        FieldKind::Choice { options, default } => {
            ("choice", format!("`{default}`"), listed(options))
        }
        FieldKind::MultiChoice {
            options,
            default,
            ordered,
            max,
        } => (
            "multi-choice",
            default
                .iter()
                .map(|key| format!("`{key}`"))
                .collect::<Vec<_>>()
                .join(", "),
            format!(
                "{}; at most {max}{}",
                listed(options),
                if *ordered {
                    ", kept in the order chosen"
                } else {
                    ""
                }
            ),
        ),
        FieldKind::Number {
            min,
            max,
            step,
            default,
            unit,
        } => {
            let unit = unit
                .as_deref()
                .map_or_else(String::new, |unit| format!(" {unit}"));
            (
                "number",
                format!("{default}{unit}"),
                format!("{min} to {max}{unit}, step {step}"),
            )
        }
        FieldKind::Text {
            default,
            max_len,
            placeholder,
        } => (
            "text",
            if default.is_empty() {
                "empty".to_owned()
            } else {
                format!("`{default}`")
            },
            match placeholder {
                Some(placeholder) => format!("up to {max_len} characters, hint \"{placeholder}\""),
                None => format!("up to {max_len} characters"),
            },
        ),
    }
}

fn listed(options: &[ChoiceOption]) -> String {
    options
        .iter()
        .map(|option| format!("`{}` ({})", option.key, option.label))
        .collect::<Vec<_>>()
        .join(", ")
}

fn on_off(value: bool) -> &'static str {
    if value { "on" } else { "off" }
}

fn contributions(text: &mut String, contributions: &[&SystemContribution]) {
    text.push_str("| Id | Kind | Title | Zone | Order | Group | Auto | Pinned |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n");
    for contribution in contributions {
        let placement = &contribution.placement;
        let _ = writeln!(
            text,
            "| `{}` | {} | {} | {} | {} | {} | {} | {} |",
            contribution.id.as_str(),
            match contribution.kind {
                ContributionKind::Panel => "panel",
                ContributionKind::Widget => "widget",
            },
            cell(contribution.title),
            match placement.zone {
                Zone::Left => "left",
                Zone::Center => "center",
                Zone::Right => "right",
            },
            placement.order,
            placement
                .group
                .map_or_else(|| "none".to_owned(), |group| format!("`{group}`")),
            match placement.auto {
                AutoPlace::Show => "show",
                AutoPlace::Tray => "tray",
            },
            yes(contribution.pinned)
        );
    }
}

fn yes(value: bool) -> &'static str {
    if value { "yes" } else { "no" }
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

#[cfg(test)]
mod tests {
    use super::*;

    const REFERENCE: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/docs/reference/plugins.md");

    #[test]
    fn plugins_reference_is_current() {
        let catalog = crate::shell_setup::plugin_catalog().expect("the application catalog");
        let rendered = render(&catalog);
        if std::env::var_os("NOCTERM_BLESS").is_some() {
            std::fs::write(REFERENCE, &rendered).expect("write the plugins reference");
            return;
        }
        let stored = std::fs::read_to_string(REFERENCE).unwrap_or_default();
        assert!(
            stored == rendered,
            "docs/reference/plugins.md is stale; run `NOCTERM_BLESS=1 cargo test -p nocterm plugins_reference` and commit the result"
        );
    }

    #[test]
    fn the_reference_lists_every_plugin_contribution_and_group_once() {
        let catalog = crate::shell_setup::plugin_catalog().expect("the application catalog");
        let rendered = render(&catalog);
        for entry in catalog.entries() {
            let row = format!("| `{}` |", entry.id.as_str());
            assert_eq!(rendered.matches(&row).count(), 1, "{}", entry.id);
        }
        for plugin in catalog.plugins() {
            assert!(rendered.contains(&format!("## {}\n", plugin.name)));
            for field in plugin.settings.fields() {
                let stored = format!(
                    "`[{}].{}`",
                    plugin.settings_section.expect("a schema needs a section"),
                    field.key
                );
                assert_eq!(rendered.matches(&stored).count(), 1, "{}", field.key);
            }
        }
        for group in catalog.groups() {
            assert!(rendered.contains(&format!("| `{}` | ", group.id.as_str())));
        }
    }
}
