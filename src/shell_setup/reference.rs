//! The plugins reference: the compiled-in system plugins and the contributions they offer.
//!
//! It is rendered from the catalog the application composes, so it cannot drift from the code.
//! A test compares it with `docs/reference/plugins.md` and rewrites that file on request.
use std::fmt::Write as _;

use nocterm_plugin_model::{
    AutoPlace, ContributionKind, PluginCatalog, SystemContribution, SystemPlugin, Zone,
};

const HEADER: &str = "<!-- Generated by `NOCTERM_BLESS=1 cargo test -p nocterm plugins_reference`. Do not edit by hand. -->\n\n";

/// The text of `docs/reference/plugins.md` for a catalog.
pub(crate) fn render(catalog: &PluginCatalog) -> String {
    let mut text = format!(
        "{HEADER}# Plugins reference\n\nThe system plugins compiled into Nocterm, and the panels and widgets they and the shell offer to the window. A contribution's placement is a hint: the Default layout places it by zone and order, and a saved layout may place it elsewhere.\n\n"
    );
    text.push_str("## Panel groups\n\nPanels in one group exclude each other. The primary group holds the sidebar.\n\n| Group | Title | Primary |\n| --- | --- | --- |\n");
    for group in catalog.groups() {
        let _ = writeln!(
            text,
            "| `{}` | {} | {} |",
            group.id.as_str(),
            cell(group.title),
            yes(group.primary)
        );
    }
    let core: Vec<_> = catalog
        .entries()
        .filter(|contribution| catalog.plugin_of(&contribution.id).is_none())
        .collect();
    text.push_str("\n## Shell\n\nContributions of the window shell and its core features. They are not plugins and cannot be switched off.\n\n");
    contributions(&mut text, &core);
    for plugin in catalog.plugins() {
        plugin_section(&mut text, plugin);
    }
    text
}

fn plugin_section(text: &mut String, plugin: &SystemPlugin) {
    let _ = write!(
        text,
        "\n## {}\n\nPlugin `{}`. Required: {}.\n\n{}\n\n",
        plugin.name,
        plugin.id.as_str(),
        yes(plugin.required),
        plugin.description
    );
    let all: Vec<_> = plugin.contributions.iter().collect();
    contributions(text, &all);
}

fn contributions(text: &mut String, contributions: &[&SystemContribution]) {
    text.push_str("| Id | Kind | Title | Zone | Order | Group | Auto | Pinned |\n| --- | --- | --- | --- | --- | --- | --- | --- |\n");
    for contribution in contributions {
        let placement = &contribution.placement;
        let _ = writeln!(
            text,
            "| `{}` | {} | {} | {} | {} | {} | {} | {} |",
            contribution.id.as_str(),
            match contribution.kind {
                ContributionKind::Panel => "panel",
                ContributionKind::Widget => "widget",
            },
            cell(contribution.title),
            match placement.zone {
                Zone::Left => "left",
                Zone::Center => "center",
                Zone::Right => "right",
            },
            placement.order,
            placement
                .group
                .map_or_else(|| "none".to_owned(), |group| format!("`{group}`")),
            match placement.auto {
                AutoPlace::Show => "show",
                AutoPlace::Tray => "tray",
            },
            yes(contribution.pinned)
        );
    }
}

fn yes(value: bool) -> &'static str {
    if value { "yes" } else { "no" }
}

fn cell(text: &str) -> String {
    text.replace('|', "\\|").replace('\n', " ")
}

#[cfg(test)]
mod tests {
    use super::*;

    const REFERENCE: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/docs/reference/plugins.md");

    #[test]
    fn plugins_reference_is_current() {
        let catalog = crate::shell_setup::plugin_catalog().expect("the application catalog");
        let rendered = render(&catalog);
        if std::env::var_os("NOCTERM_BLESS").is_some() {
            std::fs::write(REFERENCE, &rendered).expect("write the plugins reference");
            return;
        }
        let stored = std::fs::read_to_string(REFERENCE).unwrap_or_default();
        assert!(
            stored == rendered,
            "docs/reference/plugins.md is stale; run `NOCTERM_BLESS=1 cargo test -p nocterm plugins_reference` and commit the result"
        );
    }

    #[test]
    fn the_reference_lists_every_plugin_contribution_and_group_once() {
        let catalog = crate::shell_setup::plugin_catalog().expect("the application catalog");
        let rendered = render(&catalog);
        for entry in catalog.entries() {
            let row = format!("| `{}` |", entry.id.as_str());
            assert_eq!(rendered.matches(&row).count(), 1, "{}", entry.id);
        }
        for plugin in catalog.plugins() {
            assert!(rendered.contains(&format!("## {}\n", plugin.name)));
        }
        for group in catalog.groups() {
            assert!(rendered.contains(&format!("| `{}` | ", group.id.as_str())));
        }
    }
}
