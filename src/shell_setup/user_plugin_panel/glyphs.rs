//! The application's icon for each glyph a plugin view names.
use nocterm_plugin_api::Glyph;
use nocterm_ui::IconName;

/// The icon a glyph draws as. Every one is in the application's icon inventory
/// (`nocterm_ui::icons`), so none renders blank.
pub(super) fn icon_name(glyph: Glyph) -> IconName {
    match glyph {
        Glyph::Box => IconName::Box,
        Glyph::Gem => IconName::Gem,
        Glyph::Hexagon => IconName::Hexagon,
        Glyph::Plug => IconName::Plug,
        Glyph::Puzzle => IconName::Puzzle,
        Glyph::Shapes => IconName::Shapes,
        Glyph::Activity => IconName::Activity,
        Glyph::ArrowDown => IconName::ArrowDown,
        Glyph::ArrowLeft => IconName::ArrowLeft,
        Glyph::ArrowUp => IconName::ArrowUp,
        Glyph::Bell => IconName::Bell,
        Glyph::Cable => IconName::Cable,
        Glyph::Calendar => IconName::Calendar,
        Glyph::Check => IconName::Check,
        Glyph::ChevronDown => IconName::ChevronDown,
        Glyph::ChevronLeft => IconName::ChevronLeft,
        Glyph::ChevronRight => IconName::ChevronRight,
        Glyph::CircleAlert => IconName::CircleAlert,
        Glyph::CircleCheck => IconName::CircleCheck,
        Glyph::CircleX => IconName::CircleX,
        Glyph::Clock => IconName::Clock,
        Glyph::Container => IconName::Container,
        Glyph::Copy => IconName::Copy,
        Glyph::Cpu => IconName::Cpu,
        Glyph::Ellipsis => IconName::Ellipsis,
        Glyph::ExternalLink => IconName::ExternalLink,
        Glyph::Eye => IconName::Eye,
        Glyph::File => IconName::File,
        Glyph::FileText => IconName::FileText,
        Glyph::Folder => IconName::Folder,
        Glyph::FolderOpen => IconName::FolderOpen,
        Glyph::Gauge => IconName::Gauge,
        Glyph::Globe => IconName::Globe,
        Glyph::HardDrive => IconName::HardDrive,
        Glyph::Inbox => IconName::Inbox,
        Glyph::Info => IconName::Info,
        Glyph::Key => IconName::KeyRound,
        Glyph::Loader => IconName::LoaderCircle,
        Glyph::Lock => IconName::Lock,
        Glyph::Memory => IconName::MemoryStick,
        Glyph::Network => IconName::Network,
        Glyph::Pause => IconName::Pause,
        Glyph::Pencil => IconName::Pencil,
        Glyph::Play => IconName::Play,
        Glyph::Plus => IconName::Plus,
        Glyph::Minus => IconName::Minus,
        Glyph::Refresh => IconName::RefreshCw,
        Glyph::Rotate => IconName::RotateCcw,
        Glyph::Search => IconName::Search,
        Glyph::Send => IconName::Send,
        Glyph::Server => IconName::Server,
        Glyph::ServerOff => IconName::ServerOff,
        Glyph::Settings => IconName::Settings,
        Glyph::Square => IconName::Square,
        Glyph::Stop => IconName::CircleStop,
        Glyph::Star => IconName::Star,
        Glyph::Terminal => IconName::SquareTerminal,
        Glyph::Thermometer => IconName::Thermometer,
        Glyph::Trash => IconName::Trash,
        Glyph::TriangleAlert => IconName::TriangleAlert,
        Glyph::Upload => IconName::Upload,
        Glyph::User => IconName::User,
        Glyph::Wrench => IconName::Wrench,
        Glyph::X => IconName::X,
        Glyph::Zap => IconName::Zap,
        _ => IconName::Puzzle,
    }
}
